namespace ProjectTowerRpg.Core.UI
{
    // Окно с переключаемыми вкладками. Фабрика не знает, какие вкладки у окна,
    // она просто передаёт строковый токен и получает результат.
    public interface ITabbedWindow
    {
        // Открыть окно на вкладке с указанным токеном.
        // Возврат:
        //   true  — вкладка переключена (или уже была активна, но окно не хочет закрываться)
        //   false — окно уже на этой вкладке и хочет закрыться (toggle-поведение)
        bool OpenOnTabId(string tabId);
    }
}
